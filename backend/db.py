def init_db() -> None:
    settings.ANNOUNCEMENT_UPLOADS_DIR.mkdir(parents=True, exist_ok=True)
    settings.GYM_LOGOS_DIR.mkdir(parents=True, exist_ok=True)
    settings.AVATARS_DIR.mkdir(parents=True, exist_ok=True)
    connection = get_connection()
    try:
        with connection:
            _apply_schema(connection)
            seed_exercises(connection)
            seed_benchmark_workouts(connection)
            migrate_legacy_auth_terms(connection)
            ensure_added_columns(connection)
            purge_deleted_users(connection)
    finally:
        connection.close()
    seed_default_users()


def _apply_schema(connection: ManagedConnection) -> None:
    """Apply the schema idempotently. The deferred users.active_gym_id foreign key is
    added separately because it references gyms, which is created later in the script."""
    statements = SCHEMA_SQL.split(";")
    for statement in statements:
        text = statement.strip()
        if not text:
            continue
        if text.startswith("alter table users add constraint users_active_gym_id_fkey"):
            _ensure_active_gym_fk(connection, text)
        else:
            connection.execute(statement)


def _ensure_active_gym_fk(connection: ManagedConnection, statement: str) -> None:
    existing = connection.execute(
        "select 1 from pg_constraint where conname = 'users_active_gym_id_fkey'"
    ).fetchone()
    if existing is None:
        connection.execute(statement)


def seed_exercises(connection: ManagedConnection) -> None:
    """Load the bundled free-exercise-db dataset once into the exercises table.

    No-op if the table is already populated or the seed file is missing, so it
    stays cheap on every startup and harmless in environments without the data.
    """
    existing = connection.execute(
        "select count(*) as count from exercises"
    ).fetchone()
    if existing["count"] > 0:
        return
    if not settings.EXERCISES_SEED_PATH.exists():
        return
    with open(settings.EXERCISES_SEED_PATH, encoding="utf-8") as handle:
        data = json.load(handle)
    rows = []
    for item in data:
        name = str(item.get("name") or "").strip()
        if not name:
            continue
        primary = item.get("primaryMuscles") or []
        secondary = item.get("secondaryMuscles") or []
        category = str(item.get("category") or "")
        equipment = str(item.get("equipment") or "")
        search = " ".join(
            [name, " ".join(primary), " ".join(secondary), equipment, category]
        ).lower()
        rows.append(
            (
                str(item.get("id") or name),
                name,
                category,
                equipment,
                str(item.get("level") or ""),
                str(item.get("force") or ""),
                str(item.get("mechanic") or ""),
                json.dumps(primary),
                json.dumps(secondary),
                json.dumps(item.get("instructions") or []),
                search,
            )
        )
    connection.executemany(
        """
        insert into exercises (
          id, name, category, equipment, level, force, mechanic,
          primary_muscles, secondary_muscles, instructions, search
        ) values (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        on conflict (id) do nothing
        """,
        rows,
    )


def seed_benchmark_workouts(connection: ManagedConnection) -> None:
    """Load the bundled CrossFit benchmark catalog once. No-op if already
    populated or the seed file is missing."""
    existing = connection.execute(
        "select count(*) as count from benchmark_workouts"
    ).fetchone()
    if existing["count"] > 0:
        return
    if not settings.BENCHMARKS_SEED_PATH.exists():
        return
    with open(settings.BENCHMARKS_SEED_PATH, encoding="utf-8") as handle:
        data = json.load(handle)
    rows = []
    for index, item in enumerate(data):
        name = str(item.get("name") or "").strip()
        if not name:
            continue
        rows.append(
            (
                str(item.get("id") or name).lower(),
                name,
                str(item.get("category") or ""),
                json.dumps(item.get("structure") or {}),
                index,
            )
        )
    connection.executemany(
        """
        insert into benchmark_workouts (
          id, name, category, structure_json, sort_order
        ) values (?, ?, ?, ?, ?)
        on conflict (id) do nothing
        """,
        rows,
    )


def migrate_legacy_auth_terms(connection: ManagedConnection) -> None:
    connection.execute(
        "update users set account_type = 'admin' where account_type = 'owner'"
    )
    connection.execute("update users set role = 'admin' where role = 'box'")
    connection.execute(
        """
        update users
        set roles_json = replace(roles_json, '"box"', '"admin"')
        where roles_json like '%"box"%'
        """
    )
    connection.execute(
        "update gym_memberships set active_role = 'admin' where active_role = 'box'"
    )
    connection.execute(
        """
        update gym_memberships
        set roles_json = replace(roles_json, '"box"', '"admin"')
        where roles_json like '%"box"%'
        """
    )


def ensure_added_columns(connection: ManagedConnection) -> None:
    """Idempotent column backfills for tables that pre-date a column's introduction.

    Postgres supports `add column if not exists`, which we lean on so deployed
    databases pick up new columns without manual SQL. Keep this list small and
    each migration single-statement so a failure here can never half-apply.
    """
    connection.execute(
        "alter table users add column if not exists profile_image_url text not null default ''"
    )


def purge_deleted_users(connection: ManagedConnection) -> None:
    connection.execute(
        """
        delete from gym_memberships
        where user_id in (
          select id from users
          where deleted_at is not null
            and purge_after is not null
            and purge_after <= ?
        )
        """,
        (isoformat(now_utc()),),
    )
    connection.execute(
        """
        delete from gym_join_requests
        where user_id in (
          select id from users
          where deleted_at is not null
            and purge_after is not null
            and purge_after <= ?
        )
        """,
        (isoformat(now_utc()),),
    )
    connection.execute(
        """
        delete from users
        where deleted_at is not null
          and purge_after is not null
          and purge_after <= ?
        """,
        (isoformat(now_utc()),),
    )


