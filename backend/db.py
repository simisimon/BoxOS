# Rows come back as plain dicts (psycopg ``dict_row``).
Row = dict[str, Any]


def _translate(sql: str) -> str:
    """Map the codebase's ``?``-placeholder SQL onto psycopg's parameter style.

    The source statements use ``?`` placeholders and may contain literal ``%``
    characters (e.g. ``like '%"box"%'``). psycopg uses ``%s`` placeholders and
    treats ``%`` as a format marker, so literal ``%`` must be doubled first.
    """
    return sql.replace("%", "%%").replace("?", "%s")


class ManagedConnection:
    """Thin psycopg wrapper with the ergonomics the codebase relies on:
    ``connection.execute(...)`` returning a cursor, ``with connection:``
    acting as a transaction that commits on success / rolls back on error without
    closing the connection, and ``executescript`` for multi-statement DDL."""

    def __init__(self, connection: psycopg.Connection) -> None:
        self._connection = connection

    def execute(self, sql: str, params: tuple | list = ()) -> psycopg.Cursor:
        cursor = self._connection.cursor()
        cursor.execute(_translate(sql), tuple(params) if params else None)
        return cursor

    def executemany(self, sql: str, seq_of_params: list) -> None:
        cursor = self._connection.cursor()
        cursor.executemany(_translate(sql), [tuple(params) for params in seq_of_params])

    def executescript(self, sql: str) -> None:
        for statement in sql.split(";"):
            if statement.strip():
                self._connection.execute(statement)

    def __enter__(self) -> "ManagedConnection":
        return self

    def __exit__(self, exc_type, exc, tb) -> None:
        if exc_type is None:
            self._connection.commit()
        else:
            self._connection.rollback()

    def close(self) -> None:
        self._connection.close()

    def __del__(self) -> None:
        try:
            self._connection.close()
        except Exception:
            pass


def get_connection() -> ManagedConnection:
    connection = psycopg.connect(settings.DATABASE_URL, row_factory=dict_row, autocommit=False)
    return ManagedConnection(connection)


